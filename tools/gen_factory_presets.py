#!/usr/bin/env python3
"""Generate Source/FactoryPresets.h from presets/*.json (the only source of truth for the factory presets).

usage:
  python tools/gen_factory_presets.py          # rewrite the header
  python tools/gen_factory_presets.py --check  # exit 1 if the header is out of date (used by CI)

Each preset is embedded as minified JSON (key order kept) in raw string literals. Literals are split in
pieces of at most 8000 bytes (MSVC limit per literal piece is ~16 KB; adjacent literals are concatenated).
"""
import glob, json, os, sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
HEADER = os.path.join(ROOT, "Source", "FactoryPresets.h")
CHUNK = 8000
DELIM = "SCJ"


def literal(s):
    if ")" + DELIM + '"' in s:
        raise SystemExit("preset text contains the raw-string delimiter")
    pieces, b, cur = [], s.encode("utf-8"), 0
    while cur < len(b):
        end = min(len(b), cur + CHUNK)
        while end < len(b) and (b[end] & 0xC0) == 0x80:  # never split a UTF-8 character
            end -= 1
        pieces.append(b[cur:end].decode("utf-8"))
        cur = end
    return " ".join('R"' + DELIM + "(" + p + ")" + DELIM + '"' for p in pieces)


def validate(name, j):
    errs = []
    if j.get("format") != "SunoChainPreset": errs.append("format must be SunoChainPreset")
    if not isinstance(j.get("version"), int) or j["version"] > 7: errs.append("version must be an int <= 7")
    if not j.get("name"): errs.append("name missing")
    c = j.get("eq", {}).get("target_curve_db")
    if not (isinstance(c, list) and len(c) == 26): errs.append("eq.target_curve_db needs 26 values")
    v = j.get("eq", {}).get("target_curve_voiced_db")
    if v is not None and not (isinstance(v, list) and len(v) == 26): errs.append("eq.target_curve_voiced_db needs 26 values")
    s = j.get("deesser", {}).get("sib_curve_db")
    if s is not None and len(s) != 10: errs.append("deesser.sib_curve_db needs 10 values")
    if errs: raise SystemExit(name + ": " + "; ".join(errs))


def generate():
    out = ["#pragma once",
           "// Factory presets built into the plugin. GENERATED by tools/gen_factory_presets.py from presets/*.json.",
           "// Do not edit by hand: change the JSON and run the script (CI checks that this file is up to date).",
           "",
           "namespace factory",
           "{",
           "struct Preset { const char* file; const char* json; };",
           "inline const Preset presets[] = {"]
    for path in sorted(glob.glob(os.path.join(ROOT, "presets", "*.json"))):
        name = os.path.basename(path)
        with open(path, encoding="utf-8") as f:
            j = json.load(f)
        validate(name, j)
        out.append('    { "' + name + '", ' + literal(json.dumps(j, separators=(",", ":"), ensure_ascii=False)) + " },")
    out += ["};", "} // namespace factory", ""]
    return "\n".join(out)


if __name__ == "__main__":
    text = generate()
    if "--check" in sys.argv:
        with open(HEADER, encoding="utf-8") as f:
            cur = f.read()
        if cur != text:
            print("Source/FactoryPresets.h is out of date: run python tools/gen_factory_presets.py")
            sys.exit(1)
        print("FactoryPresets.h is up to date")
    else:
        with open(HEADER, "w", encoding="utf-8", newline="\n") as f:
            f.write(text)
        print("wrote", HEADER)
